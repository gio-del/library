'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { controlla } = require('../scripts/attribution.js');

// I nomi sono composti a runtime: il repo non deve contenerli per intero.
const NOME = ['Cla', 'ude'].join('');
const PRODUTTORE = ['Anthro', 'pic'].join('');
const NOREPLY = `noreply@${PRODUTTORE.toLowerCase()}.com`;

const pulito = () => ({
	title: 'feat: filtra per lingua',
	body: 'Aggiunge il filtro.',
	commits: [
		{
			sha: 'abcdef1234567',
			message: 'feat: filtra per lingua',
			authorName: 'Mario Rossi',
			authorEmail: 'mario@example.com',
			committerName: 'Mario Rossi',
			committerEmail: 'mario@example.com',
		},
	],
});

test('PR pulita passa', () => {
	assert.deepEqual(controlla(pulito()), []);
});

test(`il nome usato come soggetto non è attribuzione`, () => {
	const pr = pulito();
	pr.body = `Serve una chiave API di ${NOME}. Il produttore è ${PRODUTTORE}.`;
	pr.commits[0].message = `docs: ${NOME} come fonte dei dati`;
	assert.deepEqual(controlla(pr), []);
});

test('trailer di co-autore', () => {
	for (const t of [
		`Co-Authored-By: ${NOME} <${NOREPLY}>`,
		`co-authored-by: Qualcuno <${NOREPLY}>`,
		`CO-AUTHORED-BY: ${NOME.toUpperCase()} Code <x@example.com>`,
	]) {
		const pr = pulito();
		pr.commits[0].message += `\n\n${t}`;
		assert.equal(controlla(pr).length, 1, t);
	}
	const pr = pulito();
	pr.commits[0].message += '\n\nCo-authored-by: Mario Rossi <mario@example.com>';
	assert.deepEqual(controlla(pr), []);
});

test('trailer o link di sessione', () => {
	for (const t of [
		`https://${NOME.toLowerCase()}.ai/code/session_01ABC`,
		`${NOME}-Session: https://example.com/${NOME.toLowerCase()}/1`,
	]) {
		const pr = pulito();
		pr.body = `Fatto.\n\n${t}`;
		assert.equal(controlla(pr).length, 1, t);
	}
});

test('frasi generated/written/created/assisted', () => {
	for (const f of [
		`Generated with [${NOME} Code](https://example.com)`,
		`generated by ${NOME}`,
		`Written by ${NOME}`,
		`CREATED BY ${PRODUTTORE}`,
		`Assisted by ${NOME}`,
	]) {
		const pr = pulito();
		pr.title = f;
		assert.equal(controlla(pr).length, 1, f);
	}
});

test('emoji del robot', () => {
	const pr = pulito();
	pr.commits[0].message += '\n\n\u{1F916} fatto';
	assert.equal(controlla(pr).length, 1);
});

test('autore o committer con nome o email dell\'assistente', () => {
	for (const campo of ['authorName', 'authorEmail', 'committerName', 'committerEmail']) {
		const pr = pulito();
		pr.commits[0][campo] = campo.endsWith('Email') ? NOREPLY : `${NOME} Code`;
		assert.equal(controlla(pr).length, 1, campo);
	}
});

test('titolo e corpo della PR sono controllati', () => {
	const pr = pulito();
	pr.title = 'fix \u{1F916}';
	pr.body = `Co-authored-by: ${NOME} <${NOREPLY}>`;
	assert.equal(controlla(pr).length, 2);
});
